import { ProviderId } from '@/types/provider';
import { getModelById } from './providers';

interface MockResponseOptions {
  provider: ProviderId;
  model: string;
  prompt: string;
  onChunk: (chunk: string) => void;
  signal?: AbortSignal;
}

export function generateMockContent(provider: ProviderId, model: string, prompt: string): string {
  const modelMeta = getModelById(model);
  const modelName = modelMeta?.name || model;
  const lower = prompt.toLowerCase();

  let body = "";

  if (lower.includes("code") || lower.includes("react") || lower.includes("python") || lower.includes("function") || lower.includes("bug")) {
    body = `### Simulated Response from **${modelName}** (${provider.toUpperCase()})

Here is a clean implementation based on your request:

\`\`\`typescript
// High-performance debounce utility with TypeScript support
export function debounce<T extends (...args: any[]) => any>(
  func: T,
  waitMs: number
): (...args: Parameters<T>) => void {
  let timeoutId: ReturnType<typeof setTimeout> | null = null;

  return function (...args: Parameters<T>) {
    if (timeoutId !== null) {
      clearTimeout(timeoutId);
    }
    timeoutId = setTimeout(() => {
      func(...args);
    }, waitMs);
  };
}
\`\`\`

#### Key Highlights
- **Type Safety**: Fully typed with generics \`Parameters<T>\` and \`ReturnType<T>\`.
- **Memory Efficiency**: Ensures prior timers are cancelled before initiating new ones.
- **Provider Note**: This is running in **Mock Mode (Phase 1)**. Configure your \`${provider.toUpperCase()}_API_KEY\` in Settings to query the live API.`;
  } else if (lower.includes("compare") || lower.includes("difference") || lower.includes("vs")) {
    body = `### Comparative Analysis from **${modelName}**

When evaluating this subject, consider these primary architectural facets:

1. **Throughput & Latency**:
   - Optimal for interactive conversational workflows where low Time-To-First-Token (TTFT) is critical.
2. **Context Window**:
   - Model **${modelName}** supports up to **${modelMeta?.contextWindow ? (modelMeta.contextWindow / 1000) + 'k' : '128k'}** tokens of context.
3. **Cost Efficiency**:
   - Estimated at approximately **$${modelMeta?.pricing.inputPer1M ?? 0}/1M** input tokens and **$${modelMeta?.pricing.outputPer1M ?? 0}/1M** output tokens.

*Note: You are currently running in **Phase 1 Mock Mode**. Switch to live mode anytime once your API credentials are configured!*`;
  } else {
    body = `### Response from **${modelName}** (${provider.toUpperCase()})

Thank you for your prompt: *"${prompt.length > 60 ? prompt.substring(0, 60) + '...' : prompt}"*

As **${modelName}**, I can assist you with:
- **Software Engineering**: Full-stack web architecture, TypeScript, algorithms, and debugging.
- **Content Creation & Strategy**: High-impact documentation, technical writing, and synthesis.
- **Data & Reasoning**: Step-by-step problem decomposition and architectural critique.

> **Mock Mode Verification Notice**
> This response was generated by the **Phase 1 Mock Engine** to verify streaming UI components, message layout, and markdown rendering. Real API streaming will activate when live keys are provided in Phase 2 & 3.`;
  }

  return body;
}

/**
 * Simulates a realistic token-by-token streaming response
 */
export async function streamMockResponse({
  provider,
  model,
  prompt,
  onChunk,
  signal,
}: MockResponseOptions): Promise<{ fullText: string; promptTokens: number; completionTokens: number; durationMs: number }> {
  const fullText = generateMockContent(provider, model, prompt);
  const words = fullText.split(/(\s+)/); // split by whitespace keeping delimiters

  const startTime = Date.now();
  
  // Simulate slight initial latency (TTFT)
  await new Promise((res) => setTimeout(res, 180));

  for (let i = 0; i < words.length; i++) {
    if (signal?.aborted) {
      break;
    }
    const chunk = words[i];
    onChunk(chunk);
    
    // Random jitter between 10ms and 30ms to simulate natural token arrival
    const delay = Math.random() * 20 + 10;
    await new Promise((res) => setTimeout(res, delay));
  }

  const durationMs = Date.now() - startTime;
  const promptTokens = Math.ceil(prompt.length / 4);
  const completionTokens = Math.ceil(fullText.length / 4);

  return {
    fullText,
    promptTokens,
    completionTokens,
    durationMs,
  };
}
